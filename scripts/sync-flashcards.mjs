// Pulls the dataviz caveat flashcards from github.com/holtzy/dataviz-caveat-flashcards:
//   - sections and card titles from its README
//   - the horizontal WebP of each card, normalized to 2560×1600, into public/flashcards/
//   - a thumbnail cropped to the "not ideal / better" panels into public/flashcards/thumbs/
// and writes lib/flashcards.ts. Run again whenever cards are added (needs `cwebp`):
//   node scripts/sync-flashcards.mjs                  # new cards only
//   node scripts/sync-flashcards.mjs --force          # re-download everything
//   node scripts/sync-flashcards.mjs --from ../dataviz-caveat-flashcards
//                                                     # read a local copy instead (unpushed cards)
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";

const REPO_RAW = "https://raw.githubusercontent.com/holtzy/dataviz-caveat-flashcards/main";
const root = path.resolve(import.meta.dirname, "..");
const outDir = path.join(root, "public/flashcards");
const thumbDir = path.join(outDir, "thumbs");

// Every card has its two panels at the same place: x 7.4–92.6%, y 25–74.4% of
// a 2560×1600 card. The thumbnail keeps them with a small margin.
const CARD = { width: 2560, height: 1600 };
const CROP = { x: 128, y: 352, width: 2304, height: 880 };
const THUMB_WIDTH = 960;

const slugify = (s) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const cwebp = (...args) => execFileSync("cwebp", ["-quiet", ...args]);

// Source: GitHub by default, or a local checkout with --from <dir>.
const fromIndex = process.argv.indexOf("--from");
const localRepo = fromIndex > -1 ? path.resolve(process.argv[fromIndex + 1]) : null;
async function readSource(file) {
  if (localRepo) return fs.readFileSync(path.join(localRepo, file));
  const res = await fetch(`${REPO_RAW}/${file}`);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

const readme = (await readSource("README.md")).toString("utf8");
const sections = [];
for (const line of readme.split("\n")) {
  const heading = line.match(/^##\s+(.+)$/);
  if (heading) {
    sections.push({ id: slugify(heading[1]), title: heading[1].trim(), cards: [] });
    continue;
  }
  // "- Rank your barplot · [link](png/01-rank-your-barplot-horiz.png)"
  const card = line.match(/^-\s+(.+?)\s+·\s+\[link\]\(png\/((\d+)-[\w-]+?)-horiz\.png\)/);
  if (card && sections.length) {
    const [, title, id, number] = card;
    sections.at(-1).cards.push({
      id,
      number: Number(number),
      title,
      image: `/flashcards/${id}.webp`,
      thumb: `/flashcards/thumbs/${id}.webp`,
    });
  }
}

fs.mkdirSync(thumbDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "flashcards-"));
let synced = 0;
for (const card of sections.flatMap((s) => s.cards)) {
  const full = path.join(outDir, `${card.id}.webp`);
  const thumb = path.join(thumbDir, `${card.id}.webp`);
  if (fs.existsSync(full) && fs.existsSync(thumb) && !process.argv.includes("--force")) continue;
  const source = path.join(tmp, `${card.id}.webp`);
  fs.writeFileSync(source, await readSource(`webp/${card.id}-horiz.webp`));
  cwebp("-lossless", "-resize", String(CARD.width), String(CARD.height), source, "-o", full);
  cwebp("-q", "85", "-crop", ...[CROP.x, CROP.y, CROP.width, CROP.height].map(String), "-resize", String(THUMB_WIDTH), "0", full, "-o", thumb);
  synced++;
}
fs.rmSync(tmp, { recursive: true, force: true });

const nonEmpty = sections.filter((s) => s.cards.length);
fs.writeFileSync(
  path.join(root, "lib/flashcards.ts"),
  `// Generated by scripts/sync-flashcards.mjs from github.com/holtzy/dataviz-caveat-flashcards — do not edit by hand.

export type Flashcard = { id: string; number: number; title: string; image: string; thumb: string };
export type FlashcardSection = { id: string; title: string; cards: Flashcard[] };

/** Size of the full cards and of the thumbnails (cropped to the two panels). */
export const FLASHCARD_SIZE = { width: ${CARD.width}, height: ${CARD.height} };
export const FLASHCARD_THUMB_SIZE = { width: ${THUMB_WIDTH}, height: ${Math.round((THUMB_WIDTH * CROP.height) / CROP.width)} };

export const FLASHCARD_SECTIONS: FlashcardSection[] = ${JSON.stringify(nonEmpty, null, 2)};
`,
);
const total = nonEmpty.reduce((n, s) => n + s.cards.length, 0);
console.log(`${nonEmpty.length} sections, ${total} cards, ${synced} synced`);
